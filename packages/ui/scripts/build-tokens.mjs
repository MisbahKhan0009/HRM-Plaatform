// Generates src/tokens.css from the brand source (docs/02-brand/source/tokens.json) plus the app tokens
// from docs/02-brand/APP-UI-ADAPTATION.md. Never edit tokens.css by hand: run `pnpm tokens`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../docs/02-brand/source/tokens.json');
const out = resolve(here, '../src/tokens.css');

/** App tokens added by APP-UI-ADAPTATION.md §4 (D-040). */
const APP_COLOR_TOKENS = [
  { name: 'warn', value: { ink: '#f2b34b', paper: '#8a5300' } },
  { name: 'warn-tint', value: { ink: '#2a2112', paper: '#fff6e5' } },
  { name: 'control-border', value: { ink: '#70747b', paper: '#858585' } },
];

export function buildTokensCss(tokens) {
  const themes = tokens.color.themes.map((t) => t.id); // first theme is the default (Ink)
  const colors = [...tokens.color.tokens, ...APP_COLOR_TOKENS];
  const byName = new Map(colors.map((t) => [t.name, t]));

  const valueFor = (token, theme, seen = new Set()) => {
    const raw =
      typeof token.value === 'string' ? token.value : (token.value[theme] ?? token.value[themes[0]]);
    const alias = /^\{(.+)\}$/.exec(raw);
    if (!alias) return raw.toLowerCase();
    const target = byName.get(alias[1]);
    if (!target || seen.has(alias[1])) throw new Error(`Bad alias ${raw} in ${token.name}`);
    seen.add(alias[1]);
    return valueFor(target, theme, seen);
  };

  const block = (selector, theme) =>
    `${selector} {\n${colors.map((t) => `  --${t.name}: ${valueFor(t, theme)};`).join('\n')}\n  color-scheme: ${theme === 'paper' ? 'light' : 'dark'};\n}`;

  const scalars = [];
  for (const [family, group] of Object.entries(tokens)) {
    if (['name', 'version', 'color', 'type'].includes(family) || !group?.tokens) continue;
    for (const t of group.tokens) scalars.push(`  --${t.name}: ${t.value};`);
  }
  for (const [key, stack] of Object.entries(tokens.type.families)) scalars.push(`  --font-${key}: ${stack};`);

  return [
    '/* Generated by packages/ui/scripts/build-tokens.mjs from docs/02-brand/source/tokens.json. Do not edit. */',
    block(`:root,\n[data-theme="${themes[0]}"]`, themes[0]),
    ...themes.slice(1).map((t) => block(`[data-theme="${t}"]`, t)),
    `:root {\n${scalars.join('\n')}\n}`,
    '',
  ].join('\n\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(out, buildTokensCss(JSON.parse(readFileSync(source, 'utf8'))));
  console.log(`wrote ${out}`);
}
