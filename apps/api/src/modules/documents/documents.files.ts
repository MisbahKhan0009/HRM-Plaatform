import type { DocumentMimeType } from '@hrm/contracts';

/** Magic bytes of the allow-listed types (FR-DOC-004, SECURITY-TESTING §6). Anything else is rejected. */
const SIGNATURES: { mime: DocumentMimeType; test: (b: Uint8Array) => boolean }[] = [
  {
    mime: 'application/pdf',
    test: (b) => b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46 && b[4] === 0x2d,
  },
  {
    mime: 'image/png',
    test: (b) =>
      b[0] === 0x89 &&
      b[1] === 0x50 &&
      b[2] === 0x4e &&
      b[3] === 0x47 &&
      b[4] === 0x0d &&
      b[5] === 0x0a &&
      b[6] === 0x1a &&
      b[7] === 0x0a,
  },
  { mime: 'image/jpeg', test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  {
    mime: 'image/webp',
    test: (b) =>
      b[0] === 0x52 &&
      b[1] === 0x49 &&
      b[2] === 0x46 &&
      b[3] === 0x46 &&
      b[8] === 0x57 &&
      b[9] === 0x45 &&
      b[10] === 0x42 &&
      b[11] === 0x50,
  },
];

const EXTENSIONS: Record<DocumentMimeType, readonly string[]> = {
  'application/pdf': ['pdf'],
  'image/png': ['png'],
  'image/jpeg': ['jpg', 'jpeg'],
  'image/webp': ['webp'],
};

/** Declared types browsers send for the allow-listed files; `image/jpg` is a common alias. */
const DECLARED_ALIASES: Record<string, DocumentMimeType> = {
  'application/pdf': 'application/pdf',
  'image/png': 'image/png',
  'image/jpeg': 'image/jpeg',
  'image/jpg': 'image/jpeg',
  'image/pjpeg': 'image/jpeg',
  'image/webp': 'image/webp',
};

/** The allow-listed type the content really is, from its first bytes; `null` when it is none of them. */
export function sniffMimeType(head: Uint8Array): DocumentMimeType | null {
  return SIGNATURES.find((s) => s.test(head))?.mime ?? null;
}

const extensionOf = (name: string) => {
  const dot = name.lastIndexOf('.');
  return dot > 0 ? name.slice(dot + 1).toLowerCase() : '';
};

/**
 * Whether the declared part type and the file name extension agree with the sniffed content (US-DOC-001: a file
 * whose content does not match its extension is rejected). An empty or generic declared type is ignored.
 */
export function matchesDeclared(sniffed: DocumentMimeType, declaredType: string, fileName: string) {
  const declared = declaredType.split(';')[0]?.trim().toLowerCase() ?? '';
  if (declared && declared !== 'application/octet-stream' && DECLARED_ALIASES[declared] !== sniffed)
    return false;
  const ext = extensionOf(fileName);
  return ext === '' || EXTENSIONS[sniffed].includes(ext);
}

/**
 * A display name that is safe to store and to put in `Content-Disposition` (SECURITY-TESTING UP-05): no path,
 * no control characters, no quotes or backslashes, at most 150 characters, always with the right extension.
 */
export function safeFileName(original: string, mime: DocumentMimeType): string {
  const base = original.split(/[\\/]/).pop() ?? '';
  let name = '';
  for (const ch of base) {
    const code = ch.codePointAt(0) ?? 0;
    if (code < 0x20 || code === 0x7f || ch === '"' || ch === '\\') continue;
    name += ch;
  }
  name = name.replace(/\s+/g, ' ').trim().replace(/^\.+/, '');
  const ext = EXTENSIONS[mime][0] as string;
  if (!extensionOf(name)) name = name ? `${name}.${ext}` : `document.${ext}`;
  if (name.length > 150) {
    const suffix = `.${extensionOf(name)}`;
    name = `${name.slice(0, 150 - suffix.length)}${suffix}`;
  }
  return name;
}

/** `attachment` with an ASCII fallback and the UTF-8 name (RFC 6266), so the browser never renders the file. */
export function contentDisposition(fileName: string) {
  const ascii = fileName.replace(/[^\x20-\x7e]/g, '_').replace(/[%;]/g, '_');
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`;
}

/** R2 key generated by the server (ARCHITECTURE §5); never derived from the uploaded name. */
export const storageKey = (employeeId: string | null, documentId: string, version: number) =>
  `documents/${employeeId ?? 'company'}/${documentId}/v${version}`;

/** SHA-256 of the file content as lowercase hex (FR-DOC-005). */
export async function sha256OfBytes(bytes: Uint8Array) {
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
  let hex = '';
  for (const b of digest) hex += b.toString(16).padStart(2, '0');
  return hex;
}
